import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { downloadBase, releaseTag } from '../web/content.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = readFileSync(resolve(root, 'Sources/Meownitor/CatProfile.swift'), 'utf8');
const packs = JSON.parse(readFileSync(resolve(root, 'dist/cat-packs/cat-packs.json'), 'utf8')).packs;
const japanese = [
  ['エルサ', '白いイエネコ'], ['ホドゥ', 'コリアンショートヘア · キジトラ'], ['チーズ', 'コリアンショートヘア · 茶トラ'],
  ['モチ', 'コリアンショートヘア · 三毛'], ['コンイ', 'コリアンショートヘア · タキシード'], ['ドゥブ', 'コリアンショートヘア · 白黒'],
  ['クルム', 'ロシアンブルー'], ['ソルギ', 'ペルシャ'], ['マンドゥ', 'スコティッシュフォールド'], ['ボリ', 'シャム'], ['ソミ', 'ターキッシュアンゴラ'],
  ['オリバー', 'アメリカンショートヘア'], ['マイロ', 'ドメスティックショートヘア'], ['メープル', 'ドメスティックロングヘア'],
  ['ココ', 'シャム'], ['レオ', 'メインクーン'], ['ベラ', 'ラグドール'], ['スモーキー', 'ロシアンブルー'], ['オニキス', 'ボンベイ'], ['サニー', 'ベンガル'], ['デイジー', 'ペルシャ'],
];
const profiles = [...source.matchAll(/id:\s*"([^"]+)",\s*nameKo:\s*"([^"]+)",\s*nameEn:\s*"([^"]+)",\s*breedKo:\s*"([^"]+)",\s*breedEn:\s*"([^"]+)"/g)];
assert.equal(profiles.length, 21, 'Update the preview catalog when Swift profiles change');
assert.equal(packs.length, 17, 'Build all 17 optional packs first');
const out = resolve(root, 'web/assets');
mkdirSync(out, { recursive: true });
const cats = profiles.map(([, id, nameKo, nameEn, breedKo, breedEn], index) => {
  const bundled = ['elsa', 'K01', 'K02', 'K03'].includes(id);
  const pack = packs.find(pack => pack.id === id);
  assert.ok(bundled || pack, `Missing pack: ${id}`);
  if (pack) assert.ok(pack.url.startsWith(`${downloadBase}/`));
  const strip = resolve(root, id === 'elsa' ? 'Resources/ElsaHD/runtime/00-idle.webp' : `Resources/Cats/${id}/strips/00-idle.webp`);
  // Reuse the shipped frames; only crop/resize for a smaller website download.
  execFileSync('magick', [strip, '-crop', '1254x1254+0+0', '+repage', '-resize', '320x320', '-quality', '82', `${out}/${id}.webp`]);
  execFileSync('magick', [strip, '-resize', '2800x400', '-quality', '82', `${out}/${id}-idle.webp`]);
  return { id, name: { en: nameEn, ko: nameKo, ja: japanese[index][0] }, breed: { en: breedEn, ko: breedKo, ja: japanese[index][1] }, bundled, ...(pack ? { bytes: pack.bytes, sha256: pack.sha256, url: pack.url } : {}) };
});
execFileSync('magick', [resolve(root, 'Resources/AppIconCandidates/09-behind-monitor.png'), '-resize', '96x96', '-quality', '85', `${out}/icon.webp`]);
writeFileSync(resolve(root, 'web/cats.mjs'), `// Generated by Scripts/build-web-assets.mjs from the verified release packs.\nexport const catalog = ${JSON.stringify({ releaseTag, cats }, null, 2)};\n`);
console.log(`Generated ${cats.length} cat previews and the ${releaseTag} catalog.`);
